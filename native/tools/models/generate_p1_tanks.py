def gun(rig,s,lod):
    p=np.array([0,s.gun_y,s.gun_z]);m=Mesh();n=6 if lod else 12
    length=s.overall_length-s.length/2-s.gun_z
    m.box('paint',p+[0,0,.16],(.64,.46,.58))
    radius=.09 if s.caliber>=.12 else .075
    evacuator=.72*length if s.shape=='t55' else .46*length
    for a,b,r in ((.40,evacuator-.18,radius*1.17),(evacuator-.18,evacuator+.30,radius*1.65),(evacuator+.30,length-.30,radius)):
        assert b>a,(s.slug,length,evacuator)
        m.tube('metal_dark',p+[0,0,a],p+[0,0,b],r,n)
    hollow_muzzle(m,p+[0,0,length-.30],p+[0,0,length],radius*.90,s.caliber/2,6 if lod else 12)
    if not lod:
        for zz in np.linspace(.65,length-.45,4):m.tube('metal_dark',p+[0,0,zz],p+[0,0,zz+.04],radius*1.20,10)
        if s.shape in ('challenger','arjun','leopard1'):
            beam(m,'metal_dark',p+[.12,.12,.55],p+[.12,.12,length-.18],.025)
    m.remove_duplicates();rig.add('Gun','Turret',p,m,'X',elevation_degrees=[-8,20],positive_elevation_rotation_sign=-1,recoil_axis=[0,0,-1])
    rig.add('Muzzle','Gun',p+[0,0,length],forward=[0,0,1])


def finish(s,bottom,top,lod,details=None,cast=False):
    rig=Rig(lod);body=hull(s,lod);turret=cast_turret(s,lod) if cast else turret_mesh(s,bottom,top,lod)
    if s.era:armour_tiles(turret,body,s,lod,s.era)
    if details:details(body,turret,s,lod)
    # Small external marking carrier plates follow the turret's own side taper.
    carrier_y=s.roof-.28;blend=(carrier_y-s.deck-.12)/(s.roof-s.deck-.12)
    carrier_x=abs(bottom[3][0])*(1-blend)+abs(top[3][0])*blend+.035
    carrier_z=s.turret_z-.85
    if cast:
        carrier_y=s.deck+.40;carrier_z=s.turret_z-.40
        rx=1.36 if s.shape!='leopard1' else 1.21;rz=1.48 if s.shape=='t62' else 1.35
        carrier_x=rx*math.sqrt(1-((carrier_y-s.deck-.12)/(s.roof-s.deck-.12))**2-(.4/rz)**2)+.015
    for side in (-1,1):turret.box('paint',(side*carrier_x,carrier_y,carrier_z),(.085,.30,.58))
    body.remove_duplicates();turret.remove_duplicates()
    rig.add('Hull',rig.root,(0,0,0),body,origin='ground centre of hull footprint')
    ring=Mesh();ring.tube('metal_dark',(0,s.deck+.01,s.turret_z),(0,s.deck+.15,s.turret_z),.91,8 if lod else 24)
    rig.add('Turret_Ring','Hull',(0,s.deck+.08,s.turret_z),ring)
    rig.add('Turret','Hull',(0,s.deck+.10,s.turret_z),turret,'Y',yaw_degrees=[-180,180])
    gun(rig,s,lod);running_gear(rig,s,lod);optics_and_hatches(rig,s,lod)
    engine=s.length*.27 if s.front_engine else -s.length*.31
    rig.add('Engine_Deck','Hull',(0,s.deck+.05,engine),forward=[0,1,0])
    rig.add('Exhaust','Hull',(s.width/2-.2,1.15,s.length*.26) if s.front_engine else (0,s.deck*.75,-s.length/2-.06),forward=[1,0,0] if s.front_engine else [0,0,-1])
    marks=Mesh()
    for side in (-1,1):
        x=side*(s.width/2+.075)
        marks.face('markings',[(x,s.deck-.43,-.38),(x,s.deck-.43,.20),(x,s.deck-.16,.20),(x,s.deck-.16,-.38)],[side,0,0])
    rig.add('Markings_Hull','Hull',(0,0,0),marks)
    marks=Mesh()
    for side in (-1,1):
        x=side*(carrier_x+.046);z=carrier_z;y=carrier_y
        marks.face('markings',[(x,y-.12,z-.25),(x,y-.12,z+.25),(x,y+.12,z+.25),(x,y+.12,z-.25)],[side,0,0])
    rig.add('Markings_Turret','Turret',(0,s.deck+.10,s.turret_z),marks)
    return rig,s


