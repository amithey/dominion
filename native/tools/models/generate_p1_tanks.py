def make_wreck(rig,s):
    """Bake a burnt hull with a genuinely detached, tilted and grounded turret."""
    if s.shape=='abrams':return abrams_wreck(rig)
    body=Mesh();detached=Mesh();parts={p['name']:p for p in rig.parts}
    def on_turret(part):
        name=part['name']
        while name in parts:
            if name=='Turret':return True
            name=parts[name]['parent']
        return False
    for part in rig.parts:
        if part['mesh'] is None:continue
        mesh=part['mesh']
        if 'mesh_scale' in part['extras']:mesh=transformed(mesh,part['extras']['mesh_scale'],part['pivot'])
        merge_mesh(detached if on_turret(part) else body,mesh,roles={'paint':'metal_dark','glass':None,'markings':None})
    R=rotation((0,1,0),.93)@rotation((0,0,1),1.08)
    loose=merge_mesh(Mesh(),detached,R=R,t=[s.width+1.15,0,-.2]);low,_=loose.bounds();loose.shift([0,-low[1],0]);merge_mesh(body,loose)
    body.remove_duplicates();baked=Mesh()
    for role,g in body.groups.items():
        p=np.array(g[0]);n=np.array(g[1])
        for f in np.array(g[3]).reshape(-1,3):
            q=p[f];baked.face(role,q,np.cross(q[1]-q[0],q[2]-q[0]),normals=n[f])
    return baked


