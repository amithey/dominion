def beam(m,role,a,b,w=.035):
    a=np.array(a);b=np.array(b);axis=unit(b-a);helper=[0,1,0] if abs(axis[1])<.9 else [1,0,0]
    u=unit(np.cross(helper,axis));v=np.cross(axis,u)
    m.box(role,(a+b)/2,(w,w,np.linalg.norm(b-a)),np.stack([u,v,axis],axis=1))


def transformed(mesh,scale,pivot=(0,0,0),uv_scale=None):
    """Bake a positive scale into a copy, used for wrecks and uniform wheel parts."""
    out=Mesh();s=np.array(scale);pivot=np.array(pivot)
    for role,g in mesh.groups.items():
        p=(np.array(g[0])-pivot)*s+pivot;n=np.array(g[1])/s;n/=np.linalg.norm(n,axis=1,keepdims=True)
        out.groups[role]=[p.tolist(),n.tolist(),(np.array(g[2])*(uv_scale or 1)).tolist(),list(g[3])]
    return out


def wheel(s,lod,side):
    m=Mesh();r=s.wheel_radius;n=6 if lod else 12;steel=s.shape=='t64'
    tyre='paint' if steel else 'rubber';w=.18 if steel else .215
    if lod:profile=[(-w,0,'paint'),(-w,r,tyre),(w,r,'paint'),(w,0,'paint')]
    else:profile=[(-w,0,'paint'),(-w,r*.52,'paint'),(-w*.9,r*.87,tyre),(-w*.9,r,tyre),(-w*.35,r,'paint'),(-w*.30,r*.87,'paint'),(w*.30,r*.87,tyre),(w*.35,r,tyre),(w*.9,r,'paint'),(w*.9,r*.87,'paint'),(w,r*.52,'paint'),(w,0,'paint')]
    lathe_x(m,profile,segments=n)
    if not lod:
        m.tube('paint',(side*w,0,0),(side*(w+.04),0,0),r*.43,10)
        spokes=5 if s.shape in ('t55','t62','chonma') else 6
        for t in np.linspace(0,2*math.pi,spokes,endpoint=False):
            if s.shape in ('t55','t62','chonma'):
                beam(m,'paint',(side*(w+.02),r*.25*math.cos(t),r*.25*math.sin(t)),(side*(w+.02),r*.8*math.cos(t),r*.8*math.sin(t)),.055)
            else:m.box('metal_dark',(side*(w+.045),r*.30*math.cos(t),r*.30*math.sin(t)),(.018,.025,.025))
    return m


def running_gear(rig,s,lod):
    k=s.track_scale;x=s.width/2-.35
    zs=np.array(s.wheel_z if s.wheel_z else np.linspace(-2.43,2.43,s.wheels))*k
    for label,side in (('L',-1),('R',1)):
        for i,z in enumerate(zs):
            p=np.array([side*x,s.wheel_radius+.13*k,z]);mesh=merge_mesh(Mesh(),wheel(s,lod,side),t=p)
            rig.add(f'Wheel_{label}{i}','Hull',p,mesh,'X',radius_metres=s.wheel_radius)
        for name,z,sprocket in (('Sprocket',3.23 if s.front_engine else -3.23,True),('Idler',-3.23 if s.front_engine else 3.23,False)):
            p=np.array([side*x,.65*k,z*k]);m=transformed(end_wheel(lod,sprocket),[k,k,k],uv_scale=k)
            rig.add(name+'_'+label,'Hull',p,merge_mesh(Mesh(),m,t=p),'X')
        rollers=0 if s.shape in ('t55','t62') else (4 if s.shape=='t64' else 3)
        for i,z in enumerate(np.linspace(-1.9,1.9,rollers)):
            p=np.array([side*x,k,z*k]);m=None
            if not lod:
                m=Mesh();m.tube('rubber',p+[-.16,0,0],p+[.16,0,0],.12*k,8)
            rig.add(f'Roller_{label}{i}','Hull',p,m,'X')
        # Local YZ vertices stay UNCHANGED, including pad U and the seated path.
        # Scaling the mesh child happens after the existing shader's vertex stage.
        rig.add('Track_'+label,'Hull',(side*x,0,0),track(lod,side*x),scroll_uv='U',u_loop=[0,1],v_units='metres',
                mesh_scale=[1,k,k],canonical_track_path={'half':3.23,'radius':.57,'y':.65},track_width_metres=.66)


def hull(s,lod):
    m=Mesh();h=s.length/2;w=s.width/2-.60;y=s.deck
    profile_hull(m,'paint',[(h-.45,.40,w*.85),(h,y*.68,w*.96),(h*.40,y,w),(-h+.25,y,w*.99),(-h,y*.60,w*.90),(-h+.35,.40,w*.82)])
    for side in (-1,1):
        m.box('paint',(side*(w+.29),y-.04,0),(.59,.10,s.length-.15))
        if s.skirts:
            for z in np.linspace(-h+.65,h-.65,s.skirts):
                height=.48 if s.shape in ('t72','t64','t90','karrar','type99','vt4','type85') else .62
                m.box('paint',(side*(s.width/2-.04),y-height/2-.04,z),(.08,height,(s.length-1.05)/s.skirts-.035))
        m.box('rubber',(side*(s.width/2-.32),.62,-h+.08),(.59,.68,.055))
        m.box('paint',(side*(w-.08),y*.76,h-.035),(.24,.20,.14))
        m.box('glass',(side*(w-.08),y*.76,h+.045),(.16,.10,.025))
        if not lod:
            m.tube('metal_dark',(side*w*.7,.65,h),(side*w*.7,.65,h+.11),.065,8)
            for z in np.linspace(-h+.65,h-.65,max(4,s.skirts)):
                m.box('metal_dark',(side*(s.width/2+.006),y-.13,z),(.015,.035,.07))
    engine_z=h*.53 if s.front_engine else -h*.62
    # Separate engine grille, driver hatch, tow points and exhaust location.
    if not lod:
        for z in np.linspace(engine_z-.55,engine_z+.55,10):m.box('metal_dark',(.25 if s.front_engine else 0,y+.025,z),(1.65,.035,.055))
    driver_x=-.55 if s.front_engine else (-.48 if s.shape in ('leopard','leopard1','t55','t62','chonma') else 0)
    m.box('paint',(driver_x,y+.045,h*.35),(.58,.085,.65))
    m.box('glass',(driver_x,y+.10,h*.35+.23),(.31,.045,.09))
    m.box('metal_dark',(0,y*.75,-h-.025),(1.45,.35,.07))
    return m


