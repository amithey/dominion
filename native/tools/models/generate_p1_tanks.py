def cast_turret(s,lod):
    """Smooth cast ellipsoid, with a closed base and metre-scale curved UVs."""
    m=Mesh();rx=1.36 if s.shape!='leopard1' else 1.21;rz=1.35 if s.shape!='t62' else 1.48
    height=s.roof-s.deck-.12;base=s.deck+.12;n=12 if lod else 28;rings=3 if lod else 7
    def point(t,a):return np.array([rx*math.cos(t)*math.cos(a),base+height*math.sin(a),s.turret_z+rz*math.sin(t)*math.cos(a)])
    def normal(t,a):return unit([math.cos(t)*math.cos(a)/rx,math.sin(a)/height,math.sin(t)*math.cos(a)/rz])
    for j in range(rings):
        a=j*math.pi/2/rings;b=(j+1)*math.pi/2/rings
        for i in range(n):
            t=i*2*math.pi/n;u=(i+1)*2*math.pi/n
            coords=[(t,a),(u,a),(t,b)] if j==rings-1 else [(t,a),(u,a),(u,b),(t,b)]
            ps=[point(tt,aa) for tt,aa in coords];ns=[normal(tt,aa) for tt,aa in coords]
            uv=[[tt*(rx+rz)/2,aa*(height+rx)/2] for tt,aa in coords]
            m.face('paint',ps,np.mean(ns,axis=0),ns,uv)
    m.face('paint',[point(t,0) for t in np.linspace(0,2*math.pi,n,endpoint=False)],[0,-1,0])
    return m


def basket(m,s,lod,z=None,width=2.5):
    z=s.turret_z-1.75 if z is None else z;y=s.roof-.18
    if lod:m.box('metal_dark',(0,y,z),(width,.3,.45))
    else:
        for yy in (y-.2,y+.2):
            for zz in (z-.3,z+.3):beam(m,'metal_dark',(-width/2,yy,zz),(width/2,yy,zz),.035)
        for x in np.linspace(-width/2,width/2,8):
            beam(m,'metal_dark',(x,y-.2,z-.3),(x,y+.2,z-.3),.028)
        for x in (-width/2,width/2):beam(m,'metal_dark',(x,y+.2,z-.3),(x,y+.2,z+.3),.035)


def armour_tiles(m,hull,s,lod,style):
    """Distinct Kontakt-1 rectangular arrays versus larger modern wedge modules."""
    if style=='kontakt':
        for side in (-1,1):
            for theta in np.linspace(.25,1.10,2 if lod else 5):
                for row in range(1 if lod else 2):
                    phi=.57+row*.31;rx=1.36;rz=1.35;hh=s.roof-s.deck-.12
                    p=np.array([side*rx*math.sin(theta)*math.cos(phi),s.deck+.12+hh*math.sin(phi),s.turret_z+rz*math.cos(theta)*math.cos(phi)])
                    normal=unit([p[0]/rx**2,(p[1]-s.deck-.12)/hh**2,(p[2]-s.turret_z)/rz**2])
                    u=unit(np.cross([0,1,0],normal));v=np.cross(normal,u)
                    m.box('paint',p+normal*.035,(.49 if lod else .23,.29,.14),np.stack([u,v,normal],axis=1))
            for z in np.linspace(-s.length/2+.8,s.length/2-.8,3 if lod else 7):
                hull.box('paint',(side*(s.width/2+.01),s.deck-.24,z),(.10,.33,.83 if lod else .37))
        if not lod:
            for x in np.linspace(-.95,.95,7):hull.box('paint',(x,s.deck-.02,s.length*.34),(.24,.15,.42),rotation((1,0,0),-.20))
    else:
        for side in (-1,1):
            for j in range(2 if lod else 4):
                x=side*(.48+j*(.38 if lod else .19));z=s.turret_z+1.15-abs(x)*.42
                m.box('paint',(x,s.roof-.28,z),(.61 if lod else .29,.34,.38),rotation((0,1,0),side*.40))
